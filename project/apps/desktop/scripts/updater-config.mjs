import { writeFileSync } from 'node:fs';

const destination = process.argv[2];
const endpoint = process.env.TAURI_UPDATER_ENDPOINT?.trim() ?? '';
const pubkey = process.env.TAURI_UPDATER_PUBLIC_KEY?.trim() ?? '';
const url = URL.parse(endpoint);
if (!url || url.protocol !== 'https:' || !url.hostname || url.username || url.password || url.hash) {
  throw new Error('TAURI_UPDATER_ENDPOINT must be an HTTPS URL without credentials or a fragment.');
}

const decoded = Buffer.from(pubkey, 'base64');
const [comment, encodedKey, ...extra] = decoded.toString('utf8').trimEnd().split(/\r?\n/);
const key = Buffer.from(encodedKey ?? '', 'base64');
if (decoded.toString('base64') !== pubkey
    || !comment.startsWith('untrusted comment: ')
    || extra.length !== 0
    || key.length !== 42
    || key.subarray(0, 2).toString() !== 'Ed'
    || key.toString('base64') !== encodedKey) {
  throw new Error('TAURI_UPDATER_PUBLIC_KEY must contain the public .pub key generated by Tauri.');
}

if (!destination) throw new Error('Pass the path for the generated Tauri config override.');
const config = {
  bundle: { createUpdaterArtifacts: true },
  plugins: {
    updater: {
      endpoints: [endpoint],
      pubkey,
      requireSignedVersion: true,
    },
  },
};
writeFileSync(destination, JSON.stringify(config, null, 2) + '\n', { flag: 'wx' });
